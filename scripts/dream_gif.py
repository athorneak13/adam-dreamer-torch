"""Render what the walker world model dreams, next to what really happens.

The walker model is proprio-only: it imagines the 24-number observation vector
(7 body orientations as (xx, xz) pairs, torso height, 9 joint velocities), not pixels.
To show a dream, each decoded observation is converted back into a walker pose
(obs_to_qpos) and that pose is rendered in MuJoCo. The dream is the model's
decoded state drawn by the simulator, not images generated by the model.

Two side-by-side GIFs (left: real sim, orange; right: the dream, purple). Both
sides show the same CONTEXT real steps, then the right side runs inside the model:
  real_vs_imagined.gif  the actor picks its own actions in the dream (what training
                        does in imagination). The left side is the same policy in
                        the simulator from the same moment. Both walk, but the dream
                        is not a pose-for-pose prediction of the left side.
  dream_vs_real.gif     open-loop: the prior is fed the SAME actions the policy took
                        in the real sim. Close at first, then the dream falls over:
                        without feedback the walker is unstable (the real sim falls
                        too when these actions are replayed from a slightly
                        different state).

Usage (Pillow is only needed here, so it is not a project dependency):
  uv run --with pillow python -m scripts.dream_gif \
      --config configs/dmc_walker_walk.yaml \
      --checkpoint checkpoints/walker_h30_seed0/latest.pt --out results/dream
"""

import argparse
from pathlib import Path

import numpy as np
import torch
from PIL import Image, ImageDraw, ImageFont

from src.agent import Agent
from src.config import load_config
from src.envs.dmc_env import DMCEnvs
from src.models.distributions import symexp

# walker: bodies in obs order, and each body's parent in that list (-1 = torso root)
BODIES = ["torso", "right_thigh", "right_leg", "right_foot", "left_thigh", "left_leg", "left_foot"]
PARENT = [-1, 0, 1, 2, 0, 4, 5]
TORSO_Z_OFFSET = 1.3   # torso height = rootz + 1.3 (torso body pos in walker.xml)
DREAM_RGBA = (0.55, 0.35, 0.85, 1.0)   # dream walker colour (real walker: material "self", orange)


# ---------- observation <-> pose ----------

def obs_to_qpos(obs: np.ndarray, rootx: float) -> np.ndarray:
    """Walker proprio obs (24,) -> qpos (9,) = [rootz, rootx, rooty, 6 joints].

    Body angle = atan2(xz, xx). Torso angle = rooty, and for every other body
    child_angle = parent_angle - joint_angle, so joint = parent - child.
    rootx is not observed; the caller passes it (integrated from velocity).
    """
    ori = obs[:14].reshape(7, 2)
    ang = np.arctan2(ori[:, 1], ori[:, 0])
    joints = []
    for i in range(1, 7):
        d = ang[PARENT[i]] - ang[i]
        joints.append((d + np.pi) % (2 * np.pi) - np.pi)    # wrap to [-pi, pi)
    return np.array([obs[14] - TORSO_Z_OFFSET, rootx, ang[0], *joints])


def render_pose(physics, qpos: np.ndarray, size: int) -> np.ndarray:
    physics.data.qpos[:] = qpos
    physics.data.qvel[:] = 0.0
    physics.forward()
    return physics.render(size, size, camera_id=0)


# ---------- model rollouts ----------

def decode(agent: Agent, state: dict) -> np.ndarray:
    """RSSM state -> predicted raw observation (24,). The decoder outputs symlog(obs)."""
    wm = agent.world_model
    return symexp(wm.decoder(wm.rssm.get_feat(state)))[0].cpu().numpy()


@torch.no_grad()
def collect(agent, envs, steps, context, device, start=0):
    """Run the policy (mean action) in the real env for start + steps steps.

    The first `start` steps are not recorded (DMC resets the walker lying in a heap;
    starting mid-stride shows a dream of walking rather than of getting up).
    Returns real obs (steps, 24), actions (steps, A), real frames, the rootx track,
    and the posterior state after the last context observation.
    """
    physics = envs.envs[0].physics
    obs, is_first = envs.reset()
    state, prev_action = None, torch.zeros(1, envs.act_dim, device=device)
    real_obs, actions, frames, rootx, start_state = [], [], [], [], None
    for t in range(-start, steps):
        if t >= 0:
            real_obs.append(obs[0].copy())
            frames.append(physics.render(args.size, args.size, camera_id=0))
            rootx.append(float(physics.data.qpos[1]))
        action, state = agent.policy(torch.as_tensor(obs, device=device), state, prev_action,
                                     torch.as_tensor(is_first, device=device), sample=False)
        if t == context - 1:
            start_state = {k: v.clone() for k, v in state.items()}
        if t >= 0:
            actions.append(action[0].cpu().numpy())
        out = envs.step(action.cpu().numpy())
        obs, is_first, prev_action = out["next_obs"], out["next_is_first"], action
    return np.array(real_obs), np.array(actions), frames, np.array(rootx), start_state


@torch.no_grad()
def dream(agent, start_state, first_action, steps, real_actions=None, device="cpu"):
    """Roll the prior forward `steps` times from the last context posterior.

    real_actions given -> open-loop with those actions (a_{t-1} drives step t).
    real_actions None  -> the actor's mean action from each dreamed state.
    Returns decoded observations (steps, 24).
    """
    state, action = start_state, torch.as_tensor(first_action, device=device)[None]
    preds = []
    for k in range(steps):
        state = agent.world_model.rssm.img_step(state, action)
        preds.append(decode(agent, state))
        if real_actions is not None:
            action = torch.as_tensor(real_actions[k], device=device)[None]
        else:
            action = agent.actor(agent.world_model.rssm.get_feat(state)).mean
    return np.array(preds)


# ---------- drawing ----------

def label(img: np.ndarray, text: str, sub: str, dreaming: bool) -> Image.Image:
    im = Image.fromarray(img)
    d = ImageDraw.Draw(im)
    s = im.size[0]
    big = ImageFont.load_default(size=max(12, s // 14))
    small = ImageFont.load_default(size=max(10, s // 20))
    d.rectangle([0, 0, s, s // 7], fill=(0, 0, 0))
    d.text((8, 4), text, fill=(255, 255, 255), font=big)
    d.text((8, s // 7 + 4), sub, fill=(255, 255, 255), font=small, stroke_width=2, stroke_fill=(0, 0, 0))
    if dreaming:
        d.rectangle([0, 0, s - 1, s - 1], outline=(150, 90, 230), width=max(3, s // 64))
    return im


def save_gif(frames, path, step_ms):
    frames[0].save(path, save_all=True, append_images=frames[1:], duration=step_ms, loop=0)
    print(f"wrote {path}  ({len(frames)} frames, {path.stat().st_size / 1e6:.1f} MB)")


def main():
    cfg = load_config(args.config)
    device = torch.device("cpu")
    envs = DMCEnvs(cfg.env.name.split(":")[-1], 1, seed=args.seed, action_repeat=cfg.env.action_repeat)
    agent = Agent(cfg, envs.obs_dim, envs.act_dim).to(device).eval()
    ckpt = torch.load(args.checkpoint, map_location=device, weights_only=False)
    agent.load_state_dict(ckpt["agent"])
    torch.manual_seed(args.seed)
    dt = envs.envs[0].control_timestep() * cfg.env.action_repeat       # 0.05 s per agent step
    step_ms = int(round(dt * 1000))
    print(f"checkpoint step {ckpt['step']}, {dt:.3f} s per agent step")

    # sanity check: real obs -> qpos -> obs must round-trip
    p = envs.envs[0].physics
    envs.reset()
    for _ in range(30):
        envs.step(np.random.uniform(-1, 1, (1, envs.act_dim)))
    o = envs._obs[0].copy(); real_q = p.data.qpos.copy()
    err = np.abs(obs_to_qpos(o, real_q[1]) - real_q).max()
    print(f"obs->qpos round-trip max error: {err:.2e}")
    assert err < 1e-4, "obs_to_qpos does not invert the walker observation"

    C, H = args.context, args.dream
    real_obs, actions, real_frames, rootx, start = collect(agent, envs, C + H, C, device, start=args.start)

    # the dream is drawn by its own physics copy (own model), with the walker tinted
    # purple so "imagined" reads at a glance; the real sim keeps the default orange
    pose_physics = envs.envs[0].physics.copy(share_model=False)
    pose_physics.named.model.mat_rgba["self"] = DREAM_RGBA

    out = Path(args.out); out.mkdir(parents=True, exist_ok=True)

    def side_by_side(pred, right_title, path):
        """Left: real sim (closed loop). Right: real context frames, then the dream."""
        x = rootx[C - 1]
        frames = []
        for t in range(C + H):
            if t < C:
                sub = f"observed, step {t + 1}/{C}"
                L = label(real_frames[t], "REAL", sub, False)
                R = label(real_frames[t], right_title, sub, False)
            else:
                k = t - C
                x += pred[k][16] * dt                   # rootx velocity: obs[15:24] = qvel, qvel[1] = rootx
                img = render_pose(pose_physics, obs_to_qpos(pred[k], x), args.size)
                when = f"+{k + 1} steps ({(k + 1) * dt:.2f} s)"
                L = label(real_frames[t], "REAL", f"simulator, {when}", False)
                R = label(img, right_title, f"inside the model, {when}", True)
            canvas = Image.new("RGB", (2 * args.size + 8, args.size), (0, 0, 0))
            canvas.paste(L, (0, 0)); canvas.paste(R, (args.size + 8, 0))
            frames.append(canvas)
        save_gif(frames, path, step_ms)

    # 1. open-loop dream with the real actions (same actions on both sides)
    pred = dream(agent, start, actions[C - 1], H, real_actions=actions[C:], device=device)
    err = np.sqrt(((pred - real_obs[C:]) ** 2).mean(-1))
    print("open-loop RMSE vs real obs at dream step 1/15/30/60/100:",
          " ".join(f"{err[k - 1]:.3f}" for k in (1, 15, 30, 60, 100) if k <= H))
    side_by_side(pred, "IMAGINED, SAME ACTIONS", out / "dream_vs_real.gif")

    # 2. the actor picks its own actions in the dream; the real side is the same
    #    policy acting in the simulator from the same moment (not a pose-for-pose match)
    pred = dream(agent, start, actions[C - 1], H, real_actions=None, device=device)
    side_by_side(pred, "IMAGINED", out / "real_vs_imagined.gif")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default="configs/dmc_walker_walk.yaml")
    ap.add_argument("--checkpoint", default="checkpoints/walker_h30_seed0/latest.pt")
    ap.add_argument("--out", default="results/dream")
    ap.add_argument("--context", type=int, default=10)
    ap.add_argument("--dream", type=int, default=100)
    ap.add_argument("--start", type=int, default=100, help="policy steps before the context starts (skip getting up)")
    ap.add_argument("--seed", type=int, default=1000, help="eval env seed (not a training seed)")
    ap.add_argument("--size", type=int, default=256)
    args = ap.parse_args()
    main()
